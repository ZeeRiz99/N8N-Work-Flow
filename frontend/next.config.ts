import type { NextConfig } from "next";

// The browser talks to ONE origin (this app). /api/* is forwarded to the FastAPI backend, so the
// backend's httpOnly session cookies are first-party here. 127.0.0.1, not localhost: on Windows,
// localhost tries IPv6 first and the backend listens on IPv4.
const BACKEND_URL = process.env.BACKEND_URL ?? "http://127.0.0.1:8000";

// Security headers (P10). Next.js inlines its bootstrap scripts and styles, so 'unsafe-inline'
// is required for script/style here (documented exception in docs/SECURITY.md; nonces are the
// stricter follow-up). Everything else is same-origin only; nothing may frame the app.
const dev = process.env.NODE_ENV !== "production";
const CSP = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const SECURITY_HEADERS = [
  { key: "Content-Security-Policy", value: CSP },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: SECURITY_HEADERS }];
  },
  cacheComponents: true,
  partialPrefetching: true,
  async rewrites() {
    return [{ source: "/api/:path*", destination: `${BACKEND_URL}/api/:path*` }];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
